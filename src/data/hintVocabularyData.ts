/**
 * Searches text for known vocabulary terms and returns matching tokens.
 */
export function findVocabularyTerm(wordOrPhrase: string): VocabularyTerm | null {
  const normalized = wordOrPhrase.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim();
  if (QUEST_VOCABULARY[normalized]) {
    return QUEST_VOCABULARY[normalized];
  }
  return null;
}
